import {createHash} from "node:crypto";
import {spawnSync} from "node:child_process";
import {
  chmodSync,
  existsSync,
  mkdirSync,
  readFileSync,
  renameSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import path from "node:path";
import {fileURLToPath} from "node:url";

const packageRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const release = "v0.1.1";
const assetByPlatform = {
  "darwin:arm64": {
    name: "abapiti-darwin-arm64",
    sha256: "36a140f8c3f8e9ea506a09b5fe28c43af10dd37475d47f22f0926a15cca52e3f",
  },
  "darwin:x64": {
    name: "abapiti-darwin-amd64",
    sha256: "c844211dc3508f8e9e51cc935117e5cb31e4501819b6465e88f401ba4959a467",
  },
  "linux:arm64": {
    name: "abapiti-linux-arm64",
    sha256: "1b90aac1744794bd90a754c0485115a48b71733ecb9fd14b83a1ae4274aceda5",
  },
  "linux:x64": {
    name: "abapiti-linux-amd64",
    sha256: "e6267cd8e2d3c714d53eee1aa492b03e7f1e98c65c9bfcfcfb751016528a225f",
  },
  "win32:arm64": {
    name: "abapiti-windows-arm64.exe",
    sha256: "1ac2c2d1fd60ec7decfe9a25ca759e321c37c665ee66522acd5ad1d41ae51e1b",
  },
  "win32:x64": {
    name: "abapiti-windows-amd64.exe",
    sha256: "99a31730adb8d027abebb9275221604e4790fc2a8c570b863f45c5ac692f3189",
  },
};
const asset = assetByPlatform[`${process.platform}:${process.arch}`];
if (!asset) {
  throw new Error(`ABAPiti ${release} has no binary for ${process.platform}/${process.arch}`);
}

const cacheRoot = path.join(packageRoot, ".cache", "abapiti-release", release);
const binaryPath = path.join(cacheRoot, asset.name);
const generatedRoot = path.join(cacheRoot, "generated-output");
const finalOutput = path.join(packageRoot, `output`);
const outputManifestName = "abaplint-release-manifest.json";

function sha256(data) {
  return createHash("sha256").update(data).digest("hex");
}

function run(command, args) {
  const result = spawnSync(command, args, {
    cwd: packageRoot,
    encoding: "utf8",
    maxBuffer: 32 * 1024 * 1024,
  });
  if (result.error) {
    throw result.error;
  }
  if (result.status !== 0) {
    const detail = (result.stderr || result.stdout || "").trim();
    throw new Error(`${command} ${args.join(" ")} failed (${result.status})${detail ? `:\n${detail}` : ""}`);
  }
  return result;
}

async function ensureBinary() {
  mkdirSync(cacheRoot, {recursive: true});
  if (existsSync(binaryPath) && sha256(readFileSync(binaryPath)) === asset.sha256) {
    return;
  }

  rmSync(binaryPath, {force: true});
  const url = `https://github.com/oisee/abapiti/releases/download/${release}/${asset.name}`;
  const response = await fetch(url);
  if (!response.ok) {
    throw new Error(`Downloading ${url} failed (${response.status} ${response.statusText})`);
  }
  const contents = Buffer.from(await response.arrayBuffer());
  const actualSha256 = sha256(contents);
  if (actualSha256 !== asset.sha256) {
    throw new Error(`SHA-256 mismatch for ${asset.name}: expected ${asset.sha256}, got ${actualSha256}`);
  }

  writeFileSync(binaryPath, contents);
  if (process.platform !== "win32") {
    chmodSync(binaryPath, 0o755);
  }
}

function validateOutput() {
  for (const folder of ["a4h", "classes", "native", "osg"]) {
    if (!existsSync(path.join(generatedRoot, folder))) {
      throw new Error(`ABAPiti ${release} did not produce the expected ${folder} output under ${generatedRoot}`);
    }
  }
}

function publishOutput() {
  const existingManifest = path.join(finalOutput, outputManifestName);
  if (existsSync(finalOutput) && !existsSync(existingManifest)) {
    throw new Error(`Refusing to replace ${finalOutput}: it is not marked as generated by this script.`);
  }
  rmSync(finalOutput, {recursive: true, force: true});
  renameSync(generatedRoot, finalOutput);
}

const existingManifest = path.join(finalOutput, outputManifestName);
if (existsSync(finalOutput) && !existsSync(existingManifest)) {
  throw new Error(`Refusing to replace ${finalOutput}: it is not marked as generated by this script.`);
}

await ensureBinary();
rmSync(generatedRoot, {recursive: true, force: true});
const result = run(binaryPath, ["abaplint", "-o", generatedRoot]);
if (result.stdout) process.stdout.write(result.stdout);
if (result.stderr) process.stderr.write(result.stderr);
validateOutput();

writeFileSync(path.join(generatedRoot, outputManifestName), `${JSON.stringify({
  generatedBy: "packages/morph2/scripts/transpile-abaplint-release.mjs",
  abapitiRelease: release,
  abapitiAsset: asset.name,
  abapitiBinarySha256: asset.sha256,
  source: "abaplint bundle included in the ABAPiti release",
}, null, 2)}\n`);
publishOutput();
console.log(`Generated the bundled abaplint output under ${path.relative(packageRoot, finalOutput)}.`);
